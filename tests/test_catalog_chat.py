"""Catalog questions must use authoritative MCP metadata, never generated guesses.

These tests launch the actual stdio MCP server against a temporary SQLite store.
Document setup skips embeddings; even the chat-model readiness check is forbidden
for metadata-only requests.
"""

import re
from pathlib import Path

import pytest

from copilot.agent import Agent
from copilot.config import Settings
from copilot.library import Library
from copilot.store import Store


class NoModel:
    def status(self):
        raise AssertionError("Catalog questions must not consult model readiness")

    def chat(self, *args, **kwargs):
        raise AssertionError("Catalog facts must not be generated by a language model")


@pytest.fixture
def catalog(tmp_path):
    settings = Settings(data_dir=tmp_path / "data", ollama_url="http://127.0.0.1:9")
    store = Store(settings.database_path)
    root_path = tmp_path / "knowledge"
    root_path.mkdir()
    root = store.add_root(root_path, "Local documents")
    library = Library(settings, store)
    session = store.create_session("File inventory")
    return settings, store, root, library, session


def add_document(catalog, relative, text="Index metadata test, not an answer to inventory questions."):
    _, store, root, _, _ = catalog
    path = Path(root["path"]) / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    stat = path.stat()
    return store.upsert_document(root["id"], path, path.name, text, stat.st_mtime_ns, stat.st_size,
                                 [{"text": text, "start": 0, "end": len(text), "page": None}])


async def ask(catalog, question):
    settings, store, _, library, session = catalog
    store.add_message(session["id"], "user", question)
    result = await Agent(settings, store, library, NoModel()).respond(session["id"], question)
    assert result["mode"] == "catalog"
    assert re.search(r"\bindex(?:ed)?\b", result["content"], re.I), "Scope must be the index, not the disk"
    return result


def assert_metadata_sources(result, documents):
    sources = result["sources"]
    expected = {document["id"]: document for document in documents}
    assert {source["document_id"] for source in sources} == set(expected)
    assert len(sources) == len(expected), "One metadata source per document, not repeated search chunks"
    for number, source in enumerate(sources, 1):
        original = expected[source["document_id"]]
        assert source["title"] == original["title"]
        assert source["path"] == original["path"]
        assert source["source_number"] == number
        assert source.get("text", "") == "", "Inventory references must be metadata, not search passages"
        assert f"[{number}]" in result["content"]
        assert original["title"] in result["content"]


@pytest.mark.parametrize("question", [
    "tell the name of all the files indexed",
    "list all the files in the folder",
    "What files have I indexed?",
])
async def test_complete_inventory_uses_metadata_not_top_k_or_old_chat(catalog, question):
    _, store, root, _, session = catalog
    names = ["api.md", "deployment.md", "drive-path-repair.md", "getting-started.md",
             "verification.md", "architecture.md", "overview.txt"]
    documents = [add_document(catalog, name) for name in names]
    # The old implementation recycled incomplete retrieval/chat context as a full inventory.
    store.add_message(session["id"], "assistant", "The only indexed files are deployment.md and api.md.")
    (Path(root["path"]) / "unindexed-secret.md").write_text("Not part of the indexed catalog.")
    result = await ask(catalog, question)
    assert_metadata_sources(result, documents)
    assert re.search(r"\b7\b", result["content"])
    assert "unindexed-secret.md" not in result["content"]
    assert {step["tool"] for step in result["trace"]} == {"list_documents"}


async def test_inventory_follows_mcp_pagination_past_two_hundred(catalog):
    documents = [add_document(catalog, f"note-{number:03}.md") for number in range(205)]
    result = await ask(catalog, "List all indexed files")
    assert_metadata_sources(result, documents)
    assert re.search(r"\b205\b", result["content"])
    assert "note-204.md" in result["content"]
    assert sum(step["tool"] == "list_documents" for step in result["trace"]) >= 2


async def test_empty_inventory_is_truthful_without_model(catalog):
    result = await ask(catalog, "List all indexed files")
    assert result["sources"] == []
    assert re.search(r"\b(?:0|no|none|empty)\b", result["content"], re.I)
    assert {step["tool"] for step in result["trace"]} == {"list_documents"}


@pytest.mark.parametrize("question", [
    "is there a file names api.md",
    "Is there a file named `api.md`?",
    'Do I have a file called "api.md"?',
])
async def test_exact_filename_exists_without_self_contradiction(catalog, question):
    document = add_document(catalog, "docs/api.md", "API examples for the local service.")
    add_document(catalog, "irrelevant.md", "The answer should not be inferred from this text.")
    result = await ask(catalog, question)
    assert_metadata_sources(result, [document])
    assert not re.search(r"\b(?:not found|no match|does not exist|don't see|do not see)\b",
                         result["content"], re.I)
    assert {step["tool"] for step in result["trace"]} == {"find_documents"}


async def test_absent_filename_does_not_match_content_suffix_or_parent_directory(catalog):
    add_document(catalog, "api.md.backup", "A backup; this is not api.md.")
    add_document(catalog, "api.md/other.txt", "The parent directory is named api.md.")
    add_document(catalog, "notes.md", "api.md is mentioned in this document's contents.")
    result = await ask(catalog, "is there a file names api.md")
    assert result["sources"] == []
    assert "api.md" in result["content"]
    assert re.search(r"\b(?:no|not found|could not|couldn't|cannot|can't|isn't|is not|not in)\b",
                     result["content"], re.I)
    assert {step["tool"] for step in result["trace"]} == {"find_documents"}


async def test_duplicate_basenames_show_both_indexed_paths(catalog):
    first = add_document(catalog, "alpha/api.md")
    second = add_document(catalog, "beta/api.md")
    add_document(catalog, "beta/api.md.bak")
    result = await ask(catalog, "Does api.md exist?")
    assert_metadata_sources(result, [first, second])
    assert first["path"] in result["content"]
    assert second["path"] in result["content"]
    assert re.search(r"\b2\b", result["content"])


async def test_quoted_filename_with_spaces_is_not_split_into_search_terms(catalog):
    exact = add_document(catalog, "Study Guide.md")
    add_document(catalog, "Study.md")
    add_document(catalog, "Guide.md")
    result = await ask(catalog, 'Is there a file named "Study Guide.md"?')
    assert_metadata_sources(result, [exact])


async def test_filename_lookup_exhausts_matches_past_first_page(catalog):
    documents = [add_document(catalog, f"project-{number:03}/api.md") for number in range(205)]
    result = await ask(catalog, "Does api.md exist?")
    assert_metadata_sources(result, documents)
    assert re.search(r"\b205\b", result["content"])
    assert sum(step["tool"] == "find_documents" for step in result["trace"]) >= 2


async def test_extensionless_filename_is_an_exact_catalog_query(catalog):
    exact = add_document(catalog, "README")
    add_document(catalog, "README.md")
    result = await ask(catalog, "Do I have a file named README?")
    assert_metadata_sources(result, [exact])


async def test_missing_filename_requests_clarification_without_guessing(catalog):
    add_document(catalog, "api.md")
    result = await ask(catalog, "Is there a file?")
    assert result["sources"] == []
    assert "api.md" not in result["content"]
    assert re.search(r"\b(?:name|filename|path)\b", result["content"], re.I)
